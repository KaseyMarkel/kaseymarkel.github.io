def total(i):
    nd = nodes[i]
    if nd['kind'] == 'genus' and not nd['kids']: return nd['n']
    s = nd['n'] if nd['kind'] == 'genus' else 0
    for k in nd['kids']: s += total(k)
    nd['tot'] = s
    return s
def totn(i):
    nd = nodes[i]; return nd.get('tot', nd['n'])
