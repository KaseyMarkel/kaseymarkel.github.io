# ---------------- newick -----------------
def parse_newick(s):
    """Return (parent list, label list) in preorder. Handles quoted labels."""
    parent, label = [], []
    stack, i, n = [], 0, len(s)
    cur = None
    def new(par):
        parent.append(par); label.append(''); return len(parent) - 1
    root = new(-1); cur = root; stack = []
    def read_label(i):
        if s[i] == "'":
            j = i + 1; out = []
            while True:
                if s[j] == "'":
                    if j + 1 < n and s[j + 1] == "'": out.append("'"); j += 2; continue
                    break
                out.append(s[j]); j += 1
            return ''.join(out), j + 1
        j = i
        while j < n and s[j] not in ',();:': j += 1
        return s[i:j].replace('_', ' '), j
    while i < n:
        ch = s[i]
        if ch == '(':
            stack.append(cur); cur = new(cur); i += 1
        elif ch == ',':
            cur = new(stack[-1]); i += 1
        elif ch == ')':
            cur = stack.pop(); i += 1
        elif ch == ';': break
        elif ch == ':':
            i += 1
            while i < n and s[i] not in ',();': i += 1
        else:
            lab, i = read_label(i); label[cur] = lab
    return parent, label

def ott_of(lab):
    m = re.search(r'(ott\d+|mrcaott\d+ott\d+)$', lab.strip())
    return m.group(1) if m else None

def name_of(lab):
    m = re.match(r'^(.*?)\s*(ott\d+|mrcaott\d+ott\d+)$', lab.strip())
    return (m.group(1) if m else lab).strip()

