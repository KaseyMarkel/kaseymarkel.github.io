# ---------------- highlighted species (living wall) -----------------
def parse_wall(path):
    out, cur = [], None
    for line in open(path):
        m = re.match(r'^-\s+row:', line)
        if m: cur = {}; out.append(cur)
        m = re.match(r'^\s+(common|latin|qualifier):\s*(.*)$', line)
        if m and cur is not None:
            v = m.group(2).strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in '"\'': v = v[1:-1]
            cur[m.group(1)] = v.replace("\\'", "'")
    return out
