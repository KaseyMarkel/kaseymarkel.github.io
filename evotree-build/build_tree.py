# Node records: dict(par, kids, label, genus, n). We add genus tips as explicit children.
nodes = []
def mk(par, lab='', genus=None, n=0, kind='clade'):
    nodes.append({'par': par, 'kids': [], 'label': lab, 'genus': genus, 'n': n, 'kind': kind})
    idx = len(nodes) - 1
    if par >= 0: nodes[par]['kids'].append(idx)
    return idx

def copy(i, par):
    me = mk(par, name_of(label[i]) if not label[i].startswith('mrca') else '')
    nodes[me]['ott'] = ott_of(label[i])
    gs = genus_at.get(i, [])
    if gs and not children[i] and len(gs) == 1:
        nodes[me]['kind'] = 'genus'; nodes[me]['genus'] = gs[0]; nodes[me]['label'] = gs[0]
        nodes[me]['n'] = gen_n[gs[0]]
    else:
        for g in gs:
            mk(me, g, g, gen_n[g], 'genus')
    for c in children[i]: copy(c, me)
    return me
sys.setrecursionlimit(100000)
root = copy(0, -1)

def descend_genera(i, acc):
    if nodes[i]['kind'] == 'genus': acc.append(nodes[i]['genus'])
    for k in nodes[i]['kids']: descend_genera(k, acc)
    return acc

# Unplaced genera: hang them off the LCA of their family's placed genera.
gnode = {}
for i, nd in enumerate(nodes):
    if nd['kind'] == 'genus': gnode.setdefault(nd['genus'], i)
def path(i):
    p = []
    while i >= 0: p.append(i); i = nodes[i]['par']
    return p[::-1]
def lca(ids):
    ps = [path(i) for i in ids]
    out = ps[0][0]
    for k in range(min(map(len, ps))):
        if all(p[k] == ps[0][k] for p in ps): out = ps[0][k]
        else: break
    return out
def robust_lca(gs, frac):
    own = sum(gen_n[g] for g in gs) or 1
    cnt = collections.Counter(); dd = {}
    for g in gs:
        u = gnode[g]; w = gen_n[g] or 1e-6
        while u >= 0: cnt[u] += w; u = nodes[u]['par']
    best = None
    for u, c in cnt.items():
        if c >= frac * own:
            d = len(path(u))
            if best is None or d > best[0]: best = (d, u)
    return best[1]
